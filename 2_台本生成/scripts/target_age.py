"""商材の対象外になるネタ（65歳以上向け）を見分ける。

2026-09-29 社長判断で **65歳系のネタは作らない**。アフィリ先（退職コンシェルジュの
社会保険給付金サポート）の対象は20〜64歳で、65歳以上は最初から対象外。
「65歳の誕生日の2日前までに退職〜」は257,200再生と伸びたが、見た人がLINEに来ても
成約しない。再生だけを見る仕組み（週次レビュー・勝ち筋の再訪）に任せると
毎週ここへ戻ってくるので、リサーチ・台本・週次の3か所で同じ判定を掛ける。

64歳でも「年金を申請すると失業手当と併給調整で支給停止」のような年金受給年齢向けの
話は同じ扱いで止める（2026-09-29 社長判断）。
60歳の話（高年齢雇用継続給付など）は対象年齢の内なので止めない。
「国民年金の免除」のような現役世代向けの年金の話も止めない。
"""
from __future__ import annotations

import re
import unicodedata

OFF_TARGET = re.compile(
    r"(?:(?<!\d)(?:6[5-9]|[7-9]\d)|六十[五六七八九])\s*[歳才]"   # 65歳・70才・六十五歳
    # ただし「60歳から65歳まで支給」「65歳未満」は64歳以下の話、「65歳以上の方は対象外」
    # 「65歳を除く」は断り書きなので止めない。「65歳までに辞めないと」「65歳を過ぎると対象外」は
    # 65歳前後の退職タイミングの話なので止める
    r"(?!まで(?!に)|未満|になるまで(?!に)|以上(?:の方|の人)?は(?:対象外|除)|を除[くき])"
    r"|高年齢求職者給付"                    # 65歳以上の失業給付（一時金）
    r"|老齢[^\s、。]{0,3}年金"              # 老齢年金・老齢厚生年金
    r"|(?<!国民)年金[^\s。]{0,12}(?:同時|併給|併用|停止)"   # 失業手当と年金の同時受給・支給停止
    #   （「国民年金と国保を同時に減免」は現役世代の話なので止めない）
    r"|併給調整"
)


def off_target(text: str | None) -> str:
    """65歳系なら引っかかった語を返す。対象年齢の内なら空文字。全角数字は半角にしてから見る。"""
    m = OFF_TARGET.search(unicodedata.normalize("NFKC", text or ""))
    return m.group(0) if m else ""


def drop_lines(text: str | None) -> tuple[str, list[str]]:
    """65歳系に触れた行を抜く。返り値は（残した本文, 抜いた行）。

    重点方針のように「行ごとの指示」になっている文章から、65歳系を勧める行だけ外す。
    """
    kept, dropped = [], []
    for line in (text or "").splitlines():
        (dropped if off_target(line) else kept).append(line)
    return "\n".join(kept), [d.strip() for d in dropped]
